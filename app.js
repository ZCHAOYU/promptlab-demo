/* 第 2 层：语义检索兜底。
   只在「目标维度内」比较，加字面重叠惩罚，低于阈值直接放弃。 */
async function trySemanticFill(text) {
  window.__semanticFill = null;
  if (!text || typeof SemanticSearch === 'undefined') return;
  try {
    if (!SemanticSearch.isReady && typeof SemanticSearch.init === 'function') {
      await SemanticSearch.init();
    }
    if (!SemanticSearch.isReady) return;

    const KIND2DIM = {
      role: 'character', scene: 'scene', style: 'style',
      light: 'lighting', composition: 'composition',
      color: 'color', atmosphere: 'atmosphere'
    };
    const res = await SemanticSearch.searchMulti(text, 6, Object.keys(KIND2DIM));
    const out = {};
    Object.keys(KIND2DIM).forEach(function (kind) {
      const list = (res && res[kind]) || [];
      if (!list.length) return;
      const scored = list.map(function (it) {
        const name = it.name || it.zh || it.core || '';
        let score = typeof it.score === 'number' ? it.score : 0;
        const shared = sharedCharCount(text, name);
        // 只共享一个字（如「青梅竹马」与「竹」）说明是字面巧合，降权
        if (shared <= 1 && name.length >= 2) score -= 0.10;
        return { name: name, score: score };
      }).filter(function (x) { return x.name; });
      scored.sort(function (a, b) { return b.score - a.score; });
      const best = scored[0];
      if (best && best.score >= 0.58) out[KIND2DIM[kind]] = best.name;
    });
    window.__semanticFill = Object.keys(out).length ? out : null;
  } catch (e) {
    window.__semanticFill = null;
  }
}

