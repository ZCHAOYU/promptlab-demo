/* 中文碎片整理（2026-11-11）
   ------------------------------------------------------------
   模板是把词条字段当**句子**拼进正文的。模型有时候把 worn/outward/pose
   写成 5~6 段名词（「裱糊手茧，手指灵巧，腰/臂节扎、手握竹篾身姿、…」），
   拼出来就是名词沙拉，读不成句。

   服务端已经加了「每字段最多 3 段」的校验，但那只能拦住**新**的推理结果。
   用户浏览器 localStorage 里已经存着的坏词条不会自己变好，所以这里再做一层：
   注入词库时就把字段整理成人能读的样子。

   具体三件事：顿号/分号统一成逗号、去掉中文之间的空格、超过 3 段就截断。
   截断优先保留前半段——碎片通常越往后越跑偏。 */
function tidyZh(s, maxItems) {
  let t = String(s == null ? '' : s);
  if (!t) return '';
  t = t.replace(/[、；;／/]+/g, '，').replace(/[，,]+/g, '，');
  // 去掉 CJK 字符之间、以及标点旁边的空格
  t = t.replace(/([\u4e00-\u9fff])\s+([\u4e00-\u9fff])/g, '$1$2');
  t = t.replace(/\s*([，。！？])\s*/g, '$1');
  t = t.replace(/^[\s，。]+|[\s，。]+$/g, '');
  const parts = t.split('，').map(function (x) { return x.trim(); }).filter(Boolean);
  const lim = maxItems || 3;
  return parts.slice(0, lim).join('，');
}

function injectInferred(rec) {
  if (!rec || !rec.subject || !rec.short) return false;
  const s = rec.subject;
  const zhWorn = tidyZh(rec.worn, 3);
  const zhOutward = tidyZh(rec.outward, 3);
  const zhPose = tidyZh(rec.pose, 3);
  const zhDetail = [zhWorn, zhOutward, zhPose].filter(Boolean).join('，');
  const enWorn = (rec.en_worn || []).join(', ');

  // 性别：模型说「男/女」就把性别词并进 short。
  // 这样 alignGenderWithArchive 会自己把 fills.gender 清空，
  // 不会出现「一位中性女性社畜」这种叠词。
  let core = String(rec.short);
  const g = rec.gender || '中性';
  let prefixed = false;
  if (g === '女' && !/[女母娘婆妇姐妹妃后姑婶姨]/.test(core)) { core = '女性' + core; prefixed = true; }
  else if (g === '男' && !/[男父爷哥弟叔伯]/.test(core)) { core = '男性' + core; prefixed = true; }
  if (rec.type === 'scene') {
    if (!KW_DB.scene || !KW_DB.scene.categories) return false;
    KW_DB.scene.categories[s] = {
      core: rec.en_core,
      detail: enWorn,
      zh: { core: rec.short, detail: zhDetail },
      _infer: rec
    };
  } else if (rec.type === 'prop') {
    return false;   // 道具维度是材质/质感/展示那套，不硬套
  } else {
    if (!KW_DB.character || !KW_DB.character.categories) return false;
    KW_DB.character.categories[s] = {
      core: rec.en_core,
      detail: enWorn,
      face: '',
      pose: '',
      mood: '',
      negative: (rec.en_tags || []).join(', '),
      // 只要没在 short 前面加「男性/女性」，就别再让 fills.gender 叠一层，
      // 否则会出「一位中性玛丽苏女主」「一位中性疲惫上班族」。
      _genderNeutral: !prefixed,
      zh: {
        core: tidyZh(core, 1),
        worn: zhWorn,
        face: zhOutward,
        pose: zhPose,
        detail: zhDetail,
        carries: '',
        mood: ''
      },
      _infer: rec
    };
  }
  return true;
}

