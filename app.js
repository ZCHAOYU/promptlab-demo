/* 访问码（2026-11-11）
   ------------------------------------------------------------------
   给别人试用时，服务端可以设 PL_ACCESS_CODE。设了之后所有 /api/* 都要带
   X-PL-Code 头，否则谁都能调用 /api/infer 花你的 key。
   码来源优先级：URL 上的 ?code=xxx（存进 localStorage）> localStorage。
   这样直接发一条带码的链接给对方就行，对方不用手输。 */
function plCode() {
  try {
    var m = String(location.search || '').match(/[?&]code=([^&#]+)/);
    if (m && m[1]) {
      var c = decodeURIComponent(m[1]);
      try { localStorage.setItem('pl_code', c); } catch (e) {}
      return c;
    }
    return localStorage.getItem('pl_code') || '';
  } catch (e) { return ''; }
}

function plHeaders(extra) {
  var h = extra || {};
  var c = plCode();
  if (c) h['X-PL-Code'] = c;
  return h;
}

