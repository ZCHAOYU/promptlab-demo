const INFER_LEX_KEY = 'pl_infer_lex_v1';
const INFER_MAX_TEXT = 30;      // 太长的句子模型会瞎猜，不如弹窗问人

function inferLexLoad() {
  try {
    const raw = localStorage.getItem(INFER_LEX_KEY);
    const o = raw ? JSON.parse(raw) : {};
    return (o && typeof o === 'object') ? o : {};
  } catch (e) { return {}; }
}

function inferLexSave(lex) {
  try {
    const keys = Object.keys(lex);
    // 只留最近 200 条，别把 localStorage 塞爆
    if (keys.length > 200) {
      keys.sort((a, b) => (lex[b].ts || 0) - (lex[a].ts || 0));
      keys.slice(200).forEach(k => { delete lex[k]; });
    }
    localStorage.setItem(INFER_LEX_KEY, JSON.stringify(lex));
  } catch (e) {}
}

