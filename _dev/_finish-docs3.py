import io, os

ROOT = os.path.dirname(os.path.abspath(__file__))
PARENT = os.path.dirname(ROOT)

def edit(name, pairs):
    p = os.path.join(PARENT, name)
    s = io.open(p, encoding='utf-8').read()
    orig = s
    for a, b in pairs:
        if a not in s:
            print(f'  [MISS] {name}: {a[:44]!r}')
        s = s.replace(a, b)
    if s != orig:
        io.open(p, 'w', encoding='utf-8', newline='').write(s)
        print(f'  [OK]   {name}')

