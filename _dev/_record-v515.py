entry = '''## V5.15 — 修复：第 3 层推理的校验器把连字符当成非法字符

**日期**：2026-11-11　**类型**：修复

**怎么发现的**

给用户做端到端测试，连打 6 个新词，第 6 个「夜市烧烤摊主」失败，报错是：

```
en_worn 含非法字符：apron,t-shirt,arm_sleeves,towel
```

同一批里第一个词「茶楼说书人」也失败过一次（当时没打错误详情，只看到 ok=false）。

**根因**

`validate_infer` 里 `tags_of` 的字符白名单是 `[a-z0-9_ ()]`——**没有连字符**。
模型输出 `t-shirt` 是完完全全正确的 danbooru 风格标签，被自己的校验器判成非法，
整条推理结果作废，用户那侧看到的是「没认出主体」。

这不是罕见情况：t-shirt / u-neck / o-ring / half-length / v-neck 都很常见。
**换句话说，凡是服饰里带连字符的主体，第 3 层会稳定失败。**

第二个问题：校验不过就直接返回失败，一次都不重试。而校验失败里有一类是
「模型这次采样偏了」，换一次就过——不重试等于白白浪费一次已付费的调用。

**修法**

1. 字符白名单加连字符：`[a-z0-9_ ()\\-]`。
2. 校验失败后换一次采样再试（最多 2 轮）；仍然失败才返回，并把失败原因打到日志里
   （`[infer] 校验没过（第 N 次）：...`），下次不用靠猜。

**实测**

| | 结果 |
|---|---|
| 修前 | 6 个新词 5 成功 1 失败（失败率约 1/6）；「夜市烧烤摊主」100% 失败 |
| 修后 | 7/7 成功（含复测原来失败的那条），`apron / short_sleeves / rubber_gloves / sleevelets` 正常入库 |
| 单次耗时 | 3.3 ~ 5.4 秒（未命中缓存） |

**为什么单独开一个版本**：V5.14 已经发过版了。按规则「中间已经发过一个版就重新开一个修复版」，
不往 V5.14 里塞。

---

'''
