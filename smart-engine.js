// 基于维度结果生成负向提示词
function generateNegativePrompt(dimensions, mode) {
  const avoidSet = new Set();

  const dimMap = {
    style: 'style', lighting: 'lighting', composition: 'composition',
    color: 'color', atmosphere: 'atmosphere', quality: 'quality',
    material: 'material', texture: 'texture', display: 'display',
    background: 'background'
  };

  for (const [dim, result] of Object.entries(dimensions)) {
    if (!result || !result.value) continue;
    const ruleKey = dimMap[dim];
    if (!ruleKey || !NEGATIVE_RULES[ruleKey]) continue;

    const rules = NEGATIVE_RULES[ruleKey][result.value];
    if (rules) {
      rules.forEach(r => avoidSet.add(r));
    }
  }

  // 去重 + 排序
  const avoidList = Array.from(avoidSet);

  // 如果太短，补充通用规则
  if (avoidList.length < 3) {
    const generic = ['低质量', '模糊', '变形', '水印', '文字', '签名'];
    for (const g of generic) {
      if (!avoidSet.has(g)) avoidList.push(g);
    }
  }

  // 限制数量
  return avoidList.slice(0, 12);
}

// ============================================================
// 智能建议系统 — 基于当前模板推荐2-3个替代方案
// ============================================================
function findSuggestions(matchedTemplate, dimensions, text, mode) {
  if (!matchedTemplate) return [];

  const candidates = [];

  for (const template of SCENE_TEMPLATES) {
    // 跳过自身
    if (template.id === matchedTemplate.id) continue;
    // 同类型优先
    if (template.type !== matchedTemplate.type) continue;

    let score = 0;
    let kwOverlap = 0;

    // 关键词重叠（共享越多越相似）
    const matchedKwSet = new Set(matchedTemplate.keywords);
    for (const kw of template.keywords) {
      if (matchedKwSet.has(kw)) kwOverlap++;
    }

    // 维度重叠
    let dimOverlap = 0;
    const dimKeys = ['style', 'lighting', 'composition', 'color', 'atmosphere', 'quality'];
    for (const dk of dimKeys) {
      if (template.dimensions[dk] === matchedTemplate.dimensions[dk]) dimOverlap++;
    }

    // 差异化加分：维度不完全相同才有推荐价值
    const diffBonus = (dimKeys.length - dimOverlap) * 2;

    // 关键词重叠 + 维度差异 = 既相关又不同
    score = kwOverlap * 3 + diffBonus;

    // 用户输入文本是否能命中此模板的关键词（额外加分）
    for (const kw of template.keywords) {
      if (text.includes(kw)) score += 2;
    }

    if (score > 0) {
      candidates.push({
        template,
        score,
        reason: generateSuggestionReason(matchedTemplate, template, dimensions)
      });
    }
  }

  // 按分数降序，取前3
  candidates.sort((a, b) => b.score - a.score);
  return candidates.slice(0, 3);
}

function generateSuggestionReason(current, suggested, dimensions) {
  const reasons = [];
  const dimKeys = ['style', 'lighting', 'composition', 'color', 'atmosphere', 'quality'];

  for (const dk of dimKeys) {
    if (current.dimensions[dk] !== suggested.dimensions[dk]) {
      const label = { style:'风格', lighting:'光线', composition:'构图', color:'色彩', atmosphere:'氛围', quality:'画质' }[dk];
      if (label) reasons.push(`试试${suggested.dimensions[dk]}${label}`);
    }
  }

  if (reasons.length === 0) {
    // 如果维度完全相同，从关键词角度给建议
    const newKws = suggested.keywords.filter(k => !current.keywords.includes(k)).slice(0, 2);
    if (newKws.length > 0) {
      return `包含"${newKws.join('、')}"等元素`;
    }
    return `看看"${suggested.name}"的风格`;
  }

  return reasons.slice(0, 2).join('，');
}

// ============================================================
// SmartEngine 主入口
// ============================================================
const SmartEngine = {
  analyze(text, mode) {
    if (!text || !text.trim()) return null;

    const cleaned = cleanInput(text);
    const isScene = mode === 'scene';

    // Layer 1
    const layer1 = layer1Scoring(cleaned);

    // Layer 2
    const template = layer2TemplateMatch(cleaned, layer1, mode);

    // 长文本保护：输入 > 80 字且 Layer 1 已检测到 2+ 维度时，降低模板覆盖权重，避免强插无关元素（ISSUE-010）
    const isLongText = cleaned.length > 80;
    const layer1DimCount = Object.values(layer1).filter(l => l && l.confidence >= 50).length;
    const reduceTemplateOverride = isLongText && layer1DimCount >= 2;

    // 合并：Layer 1 缺失或低置信度 → Layer 2 补全
    const dimensions = {};
    const mergeDims = ['style', 'scene', 'lighting', 'color', 'atmosphere', 'composition', 'quality'];

    for (const dim of mergeDims) {
      const l1 = layer1[dim];
      if (l1 && l1.confidence >= 50) {
        dimensions[dim] = { ...l1 };
      } else if (template && template.dimensions[dim] && !reduceTemplateOverride) {
        dimensions[dim] = {
          value: template.dimensions[dim],
          score: 0,
          confidence: Math.min(l1 ? l1.confidence + 20 : 40, 65),
          keywords: l1 ? l1.keywords : [],
          source: 'layer2',
          templateName: template.name
        };
      } else {
        dimensions[dim] = { ...l1 };
      }
    }

    // 标记交叉推断来源
    if (dimensions.atmosphere && dimensions.atmosphere.source === 'layer1' && dimensions.atmosphere.keywords.length === 0) {
      dimensions.atmosphere.source = 'cross';
    }
    if (dimensions.color && dimensions.color.source === 'layer1' && dimensions.color.keywords.length === 0) {
      dimensions.color.source = 'cross';
    }

    // 场景模式：移除人物/性别
    if (isScene) {
      delete dimensions.character;
      delete dimensions.gender;
    } else if (mode === 'prop') {
      // 道具模式：移除人物/性别/场景，添加道具维度（优先用 Layer 1 结果）
      delete dimensions.character;
      delete dimensions.gender;
      delete dimensions.scene;
      const propDims = ['material', 'texture', 'display', 'background'];
      for (const dim of propDims) {
        const l1 = layer1[dim];
        if (l1 && l1.confidence >= 50) {
          dimensions[dim] = { ...l1 };
          // 标记交叉推断来源
          if (dimensions[dim].source === 'layer1' && dimensions[dim].keywords && dimensions[dim].keywords.length === 0) {
            dimensions[dim].source = 'cross';
          }
        } else {
          // 回退到直接检测
          const direct = detectPropDimension(cleaned, dim);
          if (direct.value) {
            dimensions[dim] = { ...direct, score: l1 ? l1.score : 0, confidence: Math.max(direct.confidence, l1 ? l1.confidence : 0) };
          } else {
            dimensions[dim] = { value: null, score: 0, confidence: 0, keywords: [], source: 'none' };
          }
        }
      }
    } else {
      if (layer1.character && layer1.character.confidence >= 50) {
        dimensions.character = { ...layer1.character };
      }
      if (layer1.gender && layer1.gender.confidence >= 50) {
        dimensions.gender = { ...layer1.gender };
      }
    }

    // Layer 3
    const reasoning = generateReasoning(dimensions);
    const expansion = generateIntentExpansion(cleaned, dimensions, template);
    const decisionSource = generateDecisionSource(dimensions);

    // 智能建议
    const suggestions = findSuggestions(template, dimensions, cleaned, mode);

    // 负向提示词
    const negativePrompt = generateNegativePrompt(dimensions, mode);

    return {
      dimensions,
      reasoning,
      expansion,
      decisionSource,
      templateName: template ? template.name : null,
      cleanedInput: cleaned,
      suggestions,
      negativePrompt
    };
  }
};

// 暴露到全局
window.SmartEngine = SmartEngine;