// 去除口语填充词 — "帮我整一个"、"那种"、"来一个"、"我想画"、"随便"
// ============================================================
const FILLER_PATTERNS = [
  /帮我[整画搞弄创作]?[一个下张幅]/g,
  /那种/g,
  /来[一个下张]/g,
  /我想[画做弄创作]/g,
  /给我[整画搞弄]?[一个下张]/g,
  /随便/g,
  /好看/g,        // 单独出现无具体指向时忽略
  /能不能/g,
  /可以吗/g,
  /谢谢/g
];

function cleanInput(text) {
  let cleaned = text;
  for (const pattern of FILLER_PATTERNS) {
    cleaned = cleaned.replace(pattern, '');
  }
  // 过滤 emoji / 特殊符号，避免误判为关键词
  cleaned = cleaned.replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}\u{200D}\u{1F1E6}-\u{1F1FF}\u{2764}\u{1F004}\u{3297}\u{3299}\u{00A9}\u{00AE}\u{2122}\u{3030}\u{303D}]/gu, '');
  return cleaned.trim().replace(/\s+/g, ' ');
}

